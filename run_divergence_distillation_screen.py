"""Patient-safe divergence screen for the retained four-qubit VQC.

This experiment changes only the VQC training objective.  Every candidate uses
the same fold-local Transformer->PLS q4 coordinates, patient-unique balanced
2,000-per-class sample, circuit, initialization, minibatch order and 30-epoch
budget.  Clinical teacher probabilities are generated by inner-fold OOF
prediction and then sigmoid-calibrated inside the outer training partition.
Folds 9 and 10 are rejected by the development access guard.
"""

